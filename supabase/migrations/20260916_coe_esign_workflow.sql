create or replace function public.request_coe_signature(
  p_document_record_id uuid,
  p_signatory_admin_user_id uuid,
  p_document_hash text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_caller record;
  v_document record;
  v_signatory record;
  v_hash text := lower(trim(coalesce(p_document_hash,'')));
begin
  select id, full_name, upper(coalesce(role,'')) as role
  into v_caller
  from public.admin_users
  where auth_user_id = auth.uid() and is_active = true
  order by created_at asc
  limit 1;
  if v_caller.id is null then raise exception 'Active admin session required.'; end if;
  if v_caller.role not in ('OWNER','HR','ADMIN','MANAGER') then raise exception 'You are not authorized to send COEs for signature.'; end if;
  if v_hash !~ '^[0-9a-f]{64}$' then raise exception 'Invalid COE content hash.'; end if;

  select id, form_key, document_no, employee_name
  into v_document
  from public.company_document_records
  where id = p_document_record_id;
  if v_document.id is null then raise exception 'COE record not found.'; end if;
  if upper(replace(coalesce(v_document.form_key,''),'_','-')) <> 'HR-COE' then raise exception 'The selected record is not a Certificate of Employment.'; end if;

  select au.id, au.full_name, cs.signatory_title
  into v_signatory
  from public.admin_users au
  join public.coe_authorized_signatories cs on cs.admin_user_id = au.id and cs.is_active = true
  where au.id = p_signatory_admin_user_id and au.is_active = true;
  if v_signatory.id is null then raise exception 'The selected COE signatory is not authorized or active.'; end if;

  insert into public.coe_signature_requests (
    document_record_id, state, requested_by_admin_user_id, assigned_signatory_admin_user_id,
    requested_at, returned_at, return_reason, signed_at, signed_name, signed_title,
    signed_signature_path, document_hash, version, released_at, updated_at
  ) values (
    p_document_record_id, 'pending', v_caller.id, v_signatory.id,
    now(), null, null, null, null, null,
    null, v_hash, 1, null, now()
  )
  on conflict (document_record_id) do update
  set state = 'pending',
      requested_by_admin_user_id = excluded.requested_by_admin_user_id,
      assigned_signatory_admin_user_id = excluded.assigned_signatory_admin_user_id,
      requested_at = now(),
      returned_at = null,
      return_reason = null,
      signed_at = null,
      signed_name = null,
      signed_title = null,
      signed_signature_path = null,
      document_hash = excluded.document_hash,
      version = public.coe_signature_requests.version + 1,
      released_at = null,
      updated_at = now();

  update public.company_document_records
  set status = 'Pending Signature', updated_at = now()
  where id = p_document_record_id;

  perform public.coe_log_signature_audit(
    'COE SENT FOR SIGNATURE',
    p_document_record_id,
    jsonb_build_object(
      'document_no',v_document.document_no,
      'employee_name',v_document.employee_name,
      'signatory_admin_user_id',v_signatory.id,
      'signatory_name',v_signatory.full_name,
      'document_hash',v_hash
    )
  );

  return jsonb_build_object('ok',true,'state','pending','document_record_id',p_document_record_id,'assigned_signatory_name',v_signatory.full_name);
end;
$$;
revoke all on function public.request_coe_signature(uuid,uuid,text) from public, anon;
grant execute on function public.request_coe_signature(uuid,uuid,text) to authenticated;

create or replace function public.get_coe_signature_state(p_document_record_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_caller record;
  v_request record;
begin
  select id, full_name, upper(coalesce(role,'')) as role
  into v_caller
  from public.admin_users
  where auth_user_id = auth.uid() and is_active = true
  order by created_at asc
  limit 1;
  if v_caller.id is null then raise exception 'Active admin session required.'; end if;

  if not exists (
    select 1 from public.company_document_records
    where id = p_document_record_id and upper(replace(coalesce(form_key,''),'_','-')) = 'HR-COE'
  ) then raise exception 'COE record not found.'; end if;

  select r.*,
         requester.full_name as requested_by_name,
         signer.full_name as assigned_signatory_name
  into v_request
  from public.coe_signature_requests r
  left join public.admin_users requester on requester.id = r.requested_by_admin_user_id
  left join public.admin_users signer on signer.id = r.assigned_signatory_admin_user_id
  where r.document_record_id = p_document_record_id;

  if v_request.document_record_id is null then
    if v_caller.role not in ('OWNER','HR','ADMIN','MANAGER') then raise exception 'You are not authorized to manage this COE.'; end if;
    return jsonb_build_object(
      'document_record_id',p_document_record_id,
      'state','draft',
      'can_sign',false,
      'can_request',true,
      'can_manage',(v_caller.role = 'OWNER')
    );
  end if;

  if not (
    v_caller.role in ('OWNER','HR','ADMIN','MANAGER')
    or v_request.requested_by_admin_user_id = v_caller.id
    or v_request.assigned_signatory_admin_user_id = v_caller.id
  ) then raise exception 'You are not authorized to access this COE signature workflow.'; end if;

  return jsonb_build_object(
    'document_record_id',v_request.document_record_id,
    'state',v_request.state,
    'requested_at',v_request.requested_at,
    'requested_by_name',v_request.requested_by_name,
    'assigned_signatory_admin_user_id',v_request.assigned_signatory_admin_user_id,
    'assigned_signatory_name',v_request.assigned_signatory_name,
    'returned_at',v_request.returned_at,
    'return_reason',v_request.return_reason,
    'signed_at',v_request.signed_at,
    'signed_name',v_request.signed_name,
    'signed_title',v_request.signed_title,
    'signed_signature_path',v_request.signed_signature_path,
    'document_hash',v_request.document_hash,
    'version',v_request.version,
    'released_at',v_request.released_at,
    'can_sign',(
      v_request.state = 'pending'
      and v_request.assigned_signatory_admin_user_id = v_caller.id
      and exists (select 1 from public.coe_authorized_signatories cs where cs.admin_user_id = v_caller.id and cs.is_active = true)
    ),
    'can_request',(v_caller.role in ('OWNER','HR','ADMIN','MANAGER')),
    'can_manage',(v_caller.role = 'OWNER')
  );
end;
$$;
revoke all on function public.get_coe_signature_state(uuid) from public, anon;
grant execute on function public.get_coe_signature_state(uuid) to authenticated;

