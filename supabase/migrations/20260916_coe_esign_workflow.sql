create or replace function public.coe_signature_storage_can_read(p_name text)
returns boolean
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_admin record;
  v_parts text[] := storage.foldername(coalesce(p_name,''));
  v_document_id uuid;
begin
  select id, upper(coalesce(role,'')) as role
  into v_admin
  from public.admin_users
  where auth_user_id = auth.uid() and is_active = true
  order by created_at asc
  limit 1;
  if v_admin.id is null then return false; end if;

  if array_length(v_parts,1) >= 2 and v_parts[1] = 'profiles' then
    return v_parts[2] = v_admin.id::text
      and exists (select 1 from public.coe_authorized_signatories cs where cs.admin_user_id = v_admin.id and cs.is_active = true);
  end if;

  if array_length(v_parts,1) >= 2 and v_parts[1] = 'documents' then
    begin v_document_id := v_parts[2]::uuid; exception when others then return false; end;
    return exists (
      select 1
      from public.coe_signature_requests r
      where r.document_record_id = v_document_id
        and r.signed_signature_path = p_name
        and r.state in ('signed','released')
        and (
          v_admin.role in ('OWNER','HR','ADMIN','MANAGER')
          or r.requested_by_admin_user_id = v_admin.id
          or r.assigned_signatory_admin_user_id = v_admin.id
        )
    );
  end if;

  return false;
end;
$$;
revoke all on function public.coe_signature_storage_can_read(text) from public, anon;
grant execute on function public.coe_signature_storage_can_read(text) to authenticated;

create or replace function public.coe_signature_storage_can_write(p_name text, p_operation text)
returns boolean
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_admin_id uuid;
  v_parts text[] := storage.foldername(coalesce(p_name,''));
  v_document_id uuid;
  v_operation text := upper(trim(coalesce(p_operation,'')));
begin
  select au.id into v_admin_id
  from public.admin_users au
  join public.coe_authorized_signatories cs on cs.admin_user_id = au.id and cs.is_active = true
  where au.auth_user_id = auth.uid() and au.is_active = true
  order by au.created_at asc
  limit 1;
  if v_admin_id is null then return false; end if;

  if array_length(v_parts,1) >= 2 and v_parts[1] = 'profiles' then
    return v_parts[2] = v_admin_id::text and v_operation in ('INSERT','UPDATE','DELETE');
  end if;

  if array_length(v_parts,1) >= 2 and v_parts[1] = 'documents' then
    begin v_document_id := v_parts[2]::uuid; exception when others then return false; end;
    return v_operation in ('INSERT','DELETE')
      and exists (
        select 1 from public.coe_signature_requests r
        where r.document_record_id = v_document_id
          and r.assigned_signatory_admin_user_id = v_admin_id
          and r.state = 'pending'
      );
  end if;

  return false;
end;
$$;
revoke all on function public.coe_signature_storage_can_write(text,text) from public, anon;
grant execute on function public.coe_signature_storage_can_write(text,text) to authenticated;

