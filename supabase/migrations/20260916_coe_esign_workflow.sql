create or replace function public.approve_coe_signature_request(
  p_document_record_id uuid,
  p_signature_storage_path text,
  p_document_hash text
)
returns jsonb
language plpgsql
security definer
set search_path = public, storage, pg_temp
as $$
declare
  v_admin record;
  v_request public.coe_signature_requests%rowtype;
  v_path text := trim(coalesce(p_signature_storage_path,''));
  v_hash text := lower(trim(coalesce(p_document_hash,'')));
  v_signed_at timestamptz := now();
begin
  select au.id, au.full_name, upper(coalesce(au.role,'')) as role, cs.signatory_title
  into v_admin
  from public.admin_users au
  join public.coe_authorized_signatories cs on cs.admin_user_id = au.id and cs.is_active = true
  where au.auth_user_id = auth.uid() and au.is_active = true
  order by au.created_at asc
  limit 1;
  if v_admin.id is null then raise exception 'Authorized signatory access required.'; end if;

  select * into v_request
  from public.coe_signature_requests
  where document_record_id = p_document_record_id
  for update;

  if v_request.document_record_id is null then raise exception 'Signature request not found.'; end if;
  if v_request.state <> 'pending' then raise exception 'This COE is no longer pending signature.'; end if;
  if v_request.assigned_signatory_admin_user_id <> v_admin.id then raise exception 'This COE is assigned to a different authorized signatory.'; end if;
  if v_hash !~ '^[0-9a-f]{64}$' or v_request.document_hash <> v_hash then raise exception 'The COE content changed after it was sent for signature.'; end if;
  if v_path = '' or v_path not like ('documents/' || p_document_record_id::text || '/%') then raise exception 'Invalid signed signature path.'; end if;

  if not exists (
    select 1 from storage.objects
    where bucket_id = 'coe-signatures' and name = v_path
  ) then raise exception 'Signed signature image was not found in secure storage.'; end if;

  update public.coe_signature_requests
  set state = 'signed',
      signed_at = v_signed_at,
      signed_name = v_admin.full_name,
      signed_title = coalesce(nullif(trim(v_admin.signatory_title),''),'Authorized Signatory'),
      signed_signature_path = v_path,
      returned_at = null,
      return_reason = null,
      updated_at = now()
  where document_record_id = p_document_record_id;

  update public.company_document_records
  set status = 'Signed',
      approved_by = v_admin.full_name,
      owner_approved_by = case when v_admin.role = 'OWNER' then v_admin.full_name else owner_approved_by end,
      owner_approved_at = case when v_admin.role = 'OWNER' then v_signed_at else owner_approved_at end,
      updated_at = now()
  where id = p_document_record_id;

  perform public.coe_log_signature_audit(
    'COE E-SIGNED AND APPROVED',
    p_document_record_id,
    jsonb_build_object('signed_name',v_admin.full_name,'signed_title',v_admin.signatory_title,'document_hash',v_hash,'signature_path',v_path)
  );

  return jsonb_build_object(
    'ok',true,
    'state','signed',
    'signed_name',v_admin.full_name,
    'signed_title',coalesce(nullif(trim(v_admin.signatory_title),''),'Authorized Signatory'),
    'signed_at',v_signed_at,
    'signed_signature_path',v_path,
    'document_hash',v_hash
  );
end;
$$;
revoke all on function public.approve_coe_signature_request(uuid,text,text) from public, anon;
grant execute on function public.approve_coe_signature_request(uuid,text,text) to authenticated;

create or replace function public.invalidate_coe_signature_if_changed(
  p_document_record_id uuid,
  p_current_document_hash text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_admin record;
  v_request public.coe_signature_requests%rowtype;
  v_hash text := lower(trim(coalesce(p_current_document_hash,'')));
begin
  select id, upper(coalesce(role,'')) as role
  into v_admin
  from public.admin_users
  where auth_user_id = auth.uid() and is_active = true
  order by created_at asc
  limit 1;
  if v_admin.id is null then raise exception 'Active admin session required.'; end if;
  if v_hash !~ '^[0-9a-f]{64}$' then raise exception 'Invalid COE content hash.'; end if;

  select * into v_request
  from public.coe_signature_requests
  where document_record_id = p_document_record_id
  for update;

  if v_request.document_record_id is null then
    if v_admin.role not in ('OWNER','HR','ADMIN','MANAGER') then raise exception 'You are not authorized to manage this COE.'; end if;
    return jsonb_build_object('document_record_id',p_document_record_id,'state','draft','document_hash',v_hash);
  end if;

  if not (
    v_admin.role in ('OWNER','HR','ADMIN','MANAGER')
    or v_request.requested_by_admin_user_id = v_admin.id
    or v_request.assigned_signatory_admin_user_id = v_admin.id
  ) then raise exception 'You are not authorized to manage this COE.'; end if;

  if v_request.state in ('signed','released') and v_request.document_hash is distinct from v_hash then
    update public.coe_signature_requests
    set state = 'draft',
        signed_at = null,
        signed_name = null,
        signed_title = null,
        signed_signature_path = null,
        document_hash = v_hash,
        released_at = null,
        updated_at = now()
    where document_record_id = p_document_record_id;

    update public.company_document_records
    set status = 'Draft', approved_by = null, updated_at = now()
    where id = p_document_record_id;

    perform public.coe_log_signature_audit(
      'COE SIGNATURE INVALIDATED AFTER CONTENT CHANGE',
      p_document_record_id,
      jsonb_build_object('previous_hash',v_request.document_hash,'current_hash',v_hash)
    );

    return jsonb_build_object('document_record_id',p_document_record_id,'state','draft','document_hash',v_hash,'signature_invalidated',true,'can_request',true);
  end if;

  return jsonb_build_object(
    'document_record_id',p_document_record_id,
    'state',v_request.state,
    'document_hash',v_request.document_hash,
    'signed_at',v_request.signed_at,
    'signed_name',v_request.signed_name,
    'signed_title',v_request.signed_title,
    'signed_signature_path',v_request.signed_signature_path,
    'signature_invalidated',false,
    'can_request',(v_admin.role in ('OWNER','HR','ADMIN','MANAGER'))
  );
end;
$$;
revoke all on function public.invalidate_coe_signature_if_changed(uuid,text) from public, anon;
grant execute on function public.invalidate_coe_signature_if_changed(uuid,text) to authenticated;

create or replace function public.log_coe_signature_output(
  p_document_record_id uuid,
  p_output_type text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_admin record;
  v_output text := upper(trim(coalesce(p_output_type,'')));
  v_request public.coe_signature_requests%rowtype;
begin
  select id, upper(coalesce(role,'')) as role
  into v_admin
  from public.admin_users
  where auth_user_id = auth.uid() and is_active = true
  order by created_at asc
  limit 1;
  if v_admin.id is null then raise exception 'Active admin session required.'; end if;
  if v_output not in ('PRINT','PDF','WORD') then raise exception 'Unsupported COE output type.'; end if;

  select * into v_request from public.coe_signature_requests where document_record_id = p_document_record_id;
  if v_request.document_record_id is null or v_request.state not in ('signed','released') then raise exception 'Final COE output requires a signed document.'; end if;
  if not (
    v_admin.role in ('OWNER','HR','ADMIN','MANAGER')
    or v_request.requested_by_admin_user_id = v_admin.id
    or v_request.assigned_signatory_admin_user_id = v_admin.id
  ) then raise exception 'You are not authorized to output this signed COE.'; end if;

  perform public.coe_log_signature_audit(
    'SIGNED COE ' || v_output || ' OUTPUT',
    p_document_record_id,
    jsonb_build_object('output_type',v_output)
  );

  return jsonb_build_object('ok',true,'output_type',v_output);
end;
$$;
