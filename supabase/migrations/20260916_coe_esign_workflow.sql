-- Roma's Donuts COE controlled e-signature workflow
-- Prepared 2026-09-16. Apply only after explicit production-migration approval.
-- Additive only: no existing COE rows are deleted or rewritten by this migration.

begin;

create table if not exists public.coe_authorized_signatories (
  admin_user_id uuid primary key references public.admin_users(id) on delete cascade,
  signatory_title text not null default 'Authorized Signatory',
  signature_profile_path text,
  is_active boolean not null default true,
  authorized_by uuid references public.admin_users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.coe_signature_requests (
  document_record_id uuid primary key references public.company_document_records(id) on delete cascade,
  state text not null default 'draft' check (state in ('draft','pending','returned','signed','released')),
  requested_by_admin_user_id uuid references public.admin_users(id) on delete set null,
  assigned_signatory_admin_user_id uuid references public.admin_users(id) on delete set null,
  requested_at timestamptz,
  returned_at timestamptz,
  return_reason text,
  signed_at timestamptz,
  signed_name text,
  signed_title text,
  signed_signature_path text,
  document_hash text,
  version integer not null default 0,
  released_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint coe_signature_hash_format check (document_hash is null or document_hash ~ '^[0-9a-f]{64}$')
);

create table if not exists public.coe_signature_audit_log (
  id bigint generated by default as identity primary key,
  document_record_id uuid references public.company_document_records(id) on delete set null,
  actor_admin_user_id uuid references public.admin_users(id) on delete set null,
  actor_name text,
  action_type text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists coe_signature_requests_assigned_state_idx
  on public.coe_signature_requests (assigned_signatory_admin_user_id, state, requested_at desc);
create index if not exists coe_signature_requests_requested_by_idx
  on public.coe_signature_requests (requested_by_admin_user_id, requested_at desc);
create index if not exists coe_signature_audit_document_idx
  on public.coe_signature_audit_log (document_record_id, created_at desc);

alter table public.coe_authorized_signatories enable row level security;
alter table public.coe_signature_requests enable row level security;
alter table public.coe_signature_audit_log enable row level security;

revoke all on table public.coe_authorized_signatories from anon, authenticated;
revoke all on table public.coe_signature_requests from anon, authenticated;
revoke all on table public.coe_signature_audit_log from anon, authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'coe-signatures',
  'coe-signatures',
  false,
  2097152,
  array['image/png','image/jpeg','image/webp']::text[]
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

create or replace function public.coe_log_signature_audit(
  p_action text,
  p_document_record_id uuid default null,
  p_details jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_admin record;
begin
  select id, full_name, upper(coalesce(role,'')) as role
  into v_admin
  from public.admin_users
  where auth_user_id = auth.uid() and is_active = true
  order by created_at asc
  limit 1;

  if v_admin.id is null then
    raise exception 'Active admin session required.';
  end if;

  insert into public.coe_signature_audit_log (
    document_record_id, actor_admin_user_id, actor_name, action_type, details
  ) values (
    p_document_record_id,
    v_admin.id,
    v_admin.full_name,
    trim(coalesce(p_action,'COE SIGNATURE ACTION')),
    coalesce(p_details, '{}'::jsonb) || jsonb_build_object('actor_role',v_admin.role)
  );
end;
$$;
revoke all on function public.coe_log_signature_audit(text,uuid,jsonb) from public, anon, authenticated;

