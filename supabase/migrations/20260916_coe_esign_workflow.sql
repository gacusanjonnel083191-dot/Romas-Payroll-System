create or replace function public.set_coe_authorized_signatory(
  p_admin_user_id uuid,
  p_enabled boolean,
  p_signatory_title text default 'Authorized Signatory'
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_owner record;
  v_target_name text;
  v_title text := nullif(trim(coalesce(p_signatory_title,'')), '');
begin
  select id, full_name, upper(coalesce(role,'')) as role
  into v_owner
  from public.admin_users
  where auth_user_id = auth.uid()
    and is_active = true
    and upper(coalesce(role,'')) = 'OWNER'
  order by created_at asc
  limit 1;

  if v_owner.id is null then raise exception 'Owner authorization required.'; end if;

  select full_name into v_target_name
  from public.admin_users
  where id = p_admin_user_id and is_active = true;

  if v_target_name is null then raise exception 'The selected admin account is not active.'; end if;

  insert into public.coe_authorized_signatories (
    admin_user_id, signatory_title, is_active, authorized_by, updated_at
  ) values (
    p_admin_user_id, coalesce(v_title,'Authorized Signatory'), coalesce(p_enabled,false), v_owner.id, now()
  )
  on conflict (admin_user_id) do update
  set signatory_title = excluded.signatory_title,
      is_active = excluded.is_active,
      authorized_by = excluded.authorized_by,
      updated_at = now();

  perform public.coe_log_signature_audit(
    case when p_enabled then 'COE SIGNATORY AUTHORIZED' else 'COE SIGNATORY DISABLED' end,
    null,
    jsonb_build_object('target_admin_user_id',p_admin_user_id,'target_name',v_target_name,'signatory_title',coalesce(v_title,'Authorized Signatory'))
  );

  return jsonb_build_object('ok',true,'admin_user_id',p_admin_user_id,'authorized',coalesce(p_enabled,false));
end;
$$;
revoke all on function public.set_coe_authorized_signatory(uuid,boolean,text) from public, anon;
